package org.fenixedu.bennu.saml.client;

import java.util.function.Consumer;

import javax.xml.namespace.QName;

import org.opensaml.core.xml.XMLObject;
import org.opensaml.core.xml.config.XMLObjectProviderRegistrySupport;
import org.opensaml.saml.saml2.metadata.AttributeConsumingService;
import org.opensaml.saml.saml2.metadata.ContactPerson;
import org.opensaml.saml.saml2.metadata.ContactPersonTypeEnumeration;
import org.opensaml.saml.saml2.metadata.EmailAddress;
import org.opensaml.saml.saml2.metadata.EntityDescriptor;
import org.opensaml.saml.saml2.metadata.GivenName;
import org.opensaml.saml.saml2.metadata.LocalizedName;
import org.opensaml.saml.saml2.metadata.Organization;
import org.opensaml.saml.saml2.metadata.OrganizationDisplayName;
import org.opensaml.saml.saml2.metadata.OrganizationName;
import org.opensaml.saml.saml2.metadata.OrganizationURL;
import org.opensaml.saml.saml2.metadata.RequestedAttribute;
import org.opensaml.saml.saml2.metadata.ServiceName;
import org.opensaml.saml.saml2.metadata.SPSSODescriptor;
import org.opensaml.saml.saml2.metadata.SurName;
import org.springframework.security.saml2.provider.service.metadata.OpenSamlMetadataResolver;

/**
 * Enriches the SP metadata generated by Spring Security (which by default emits no organization,
 * contacts or attribute requests) with the values configured through the {@code saml.organization.*},
 * {@code saml.contact.*} and {@code saml.service.name} configuration keys.
 */
public class BennuSaml2MetadataPostProcessor implements Consumer<OpenSamlMetadataResolver.EntityDescriptorParameters> {

    @Override
    public void accept(OpenSamlMetadataResolver.EntityDescriptorParameters parameters) {
        EntityDescriptor entityDescriptor = parameters.getEntityDescriptor();
        SPSSODescriptor spDescriptor = (SPSSODescriptor) entityDescriptor
                .getRoleDescriptors(SPSSODescriptor.DEFAULT_ELEMENT_NAME)
                .get(0);

        addOrganization(spDescriptor);
        addContactPerson(spDescriptor);
        addAttributeConsumingService(spDescriptor);
    }

    private void addOrganization(SPSSODescriptor spDescriptor) {
        SAMLClientConfiguration.ConfigurationProperties config = SAMLClientConfiguration.getConfiguration();
        String name = config.organizationName();
        String displayName = config.organizationDisplayName();
        String url = config.organizationUrl();
        if (isBlank(name) && isBlank(displayName) && isBlank(url)) {
            return;
        }
        String lang = firstNonBlank(config.organizationLang(), "en");
        Organization organization = build(Organization.DEFAULT_ELEMENT_NAME);
        if (!isBlank(name)) {
            organization.getOrganizationNames().add(localized(OrganizationName.DEFAULT_ELEMENT_NAME, name, lang));
        }
        if (!isBlank(displayName)) {
            organization.getDisplayNames().add(localized(OrganizationDisplayName.DEFAULT_ELEMENT_NAME, displayName, lang));
        }
        if (!isBlank(url)) {
            OrganizationURL localizedUrl = build(OrganizationURL.DEFAULT_ELEMENT_NAME);
            localizedUrl.setValue(url);
            localizedUrl.setXMLLang(lang);
            organization.getURLs().add(localizedUrl);
        }
        spDescriptor.setOrganization(organization);
    }

    private void addContactPerson(SPSSODescriptor spDescriptor) {
        SAMLClientConfiguration.ConfigurationProperties config = SAMLClientConfiguration.getConfiguration();
        String email = config.contactEmail();
        if (isBlank(email) && isBlank(config.contactGivenName()) && isBlank(config.contactSurname())) {
            return;
        }
        ContactPerson contact = build(ContactPerson.DEFAULT_ELEMENT_NAME);
        contact.setType(contactType(config.contactType()));
        if (!isBlank(config.contactGivenName())) {
            GivenName givenName = build(GivenName.DEFAULT_ELEMENT_NAME);
            givenName.setName(config.contactGivenName());
            contact.setGivenName(givenName);
        }
        if (!isBlank(config.contactSurname())) {
            SurName surName = build(SurName.DEFAULT_ELEMENT_NAME);
            surName.setName(config.contactSurname());
            contact.setSurName(surName);
        }
        if (!isBlank(email)) {
            EmailAddress emailAddress = build(EmailAddress.DEFAULT_ELEMENT_NAME);
            emailAddress.setAddress(email);
            contact.getEmailAddresses().add(emailAddress);
        }
        spDescriptor.getContactPersons().add(contact);
    }

    private void addAttributeConsumingService(SPSSODescriptor spDescriptor) {
        SAMLClientConfiguration.ConfigurationProperties config = SAMLClientConfiguration.getConfiguration();
        String serviceName = config.serviceName();
        String usernameAttribute = config.usernameAttribute();
        if (isBlank(serviceName)) {
            return;
        }
        String lang = firstNonBlank(config.organizationLang(), "en");
        AttributeConsumingService service = build(AttributeConsumingService.DEFAULT_ELEMENT_NAME);
        service.setIndex(0);
        service.setIsDefault(Boolean.TRUE);
        service.getNames().add(localized(ServiceName.DEFAULT_ELEMENT_NAME, serviceName, lang));
        RequestedAttribute requestedAttribute = build(RequestedAttribute.DEFAULT_ELEMENT_NAME);
        requestedAttribute.setName(usernameAttribute);
        service.getRequestAttributes().add(requestedAttribute);
        spDescriptor.getAttributeConsumingServices().add(service);
    }

    private ContactPersonTypeEnumeration contactType(String type) {
        if (type == null) {
            return ContactPersonTypeEnumeration.TECHNICAL;
        }
        switch (type.trim().toLowerCase()) {
            case "support":
                return ContactPersonTypeEnumeration.SUPPORT;
            case "administrative":
                return ContactPersonTypeEnumeration.ADMINISTRATIVE;
            case "billing":
                return ContactPersonTypeEnumeration.BILLING;
            case "other":
                return ContactPersonTypeEnumeration.OTHER;
            case "technical":
            default:
                return ContactPersonTypeEnumeration.TECHNICAL;
        }
    }

    private <T extends LocalizedName> T localized(QName elementName, String value, String lang) {
        T localized = build(elementName);
        localized.setValue(value);
        localized.setXMLLang(lang);
        return localized;
    }

    private static <T extends XMLObject> T build(QName elementName) {
        return (T) XMLObjectProviderRegistrySupport.getBuilderFactory().getBuilder(elementName)
                .buildObject(elementName);
    }

    private static boolean isBlank(String value) {
        return value == null || value.trim().isEmpty();
    }

    private static String firstNonBlank(String first, String second) {
        return isBlank(first) ? second : first;
    }
}
